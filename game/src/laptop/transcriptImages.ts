import type { ImageOmittedPart, ImagePart, ImageRef, TranscriptItem } from '../net/protocol';
import { h, ICON, icon } from '../ui/dom';
import { openImageLightbox, originLabel, unavailableText } from '../ui/imageLightbox';
import type { ImageFeed } from './imageFeed';

/**
 * M16 phase 2: images in the conversation.
 *
 * - A message's images (`parts`) and a tool row's (`images`) are one wrapping strip of thumbnails, at most 480 px on the
 *   longest side (a lone image gets the room, several share the row). A thumbnail is fetched when it scrolls into view
 *   (IntersectionObserver) and only for a hash the bridge sent; a click opens the lightbox on the strip's images. A tool
 *   row's strip shows under its header with the row collapsed, and alone while tool calls are hidden (#70).
 * - Images that are not available (a path outside the bridge's roots, a file that is gone, a URL, bytes that are no
 *   image) are a compact card with the path as text. Nothing here ever builds a path or a URL of its own: the only
 *   `src` is an object URL the feed made from bytes the bridge sent.
 * - Grouping (`imageRuns`): consecutive image-only items share one strip; see the rule there.
 */

export type AnyImagePart = ImagePart | ImageOmittedPart | { text: string };

export const isImagePart = (p: unknown): p is ImagePart => !!p && typeof p === 'object' && 'image' in p && !!(p as ImagePart).image && typeof (p as ImagePart).image === 'object';
export const isOmittedPart = (p: unknown): p is ImageOmittedPart => !!p && typeof p === 'object' && 'image_omitted' in p;
const isTextPart = (p: unknown): p is { text: string } => !!p && typeof p === 'object' && typeof (p as { text?: unknown }).text === 'string';

/** The image parts of a message or tool output: refs, and older bridges' placeholders as unavailable ones. */
export function imagesOf(parts: readonly unknown[] | undefined): ImageRef[] {
  const out: ImageRef[] = [];
  for (const p of Array.isArray(parts) ? parts : []) {
    if (isImagePart(p)) out.push(p.image);
    else if (isOmittedPart(p)) out.push({ source: 'inline', origin: 'input', unavailable: true, reason: 'omitted' });
  }
  return out;
}

/**
 * The grouping rule. An item is **image-only** when it is a `user` or `assistant` item with at least one image part and no
 * part with text (a part of only whitespace is none). Consecutive image-only items share one strip (`ids` of a run, in
 * order) when they have the **same role** (`kind`: a `user` and an `assistant` image are never one strip). A run breaks at
 *
 * - an item with a text part (whatever its role),
 * - any other visible row: a tool, subagent, thinking, compaction or notice row, or an unknown one,
 * - a change of role.
 *
 * Rows the view hides (the bridge's `hidden` ones and unknown entries, unless "show system" is on) are not rows, so they do
 * not break a run. Grouping is only within one timeline (a subagent's nested one groups its own).
 */
export function imageRuns(items: readonly TranscriptItem[], showSystem: boolean): string[][] {
  const runs: string[][] = [];
  let cur: { kind: string; ids: string[] } | null = null;
  for (const it of items) {
    if (!showSystem && (it.hidden === true || it.kind === 'unknown')) continue;
    if (isImageOnly(it)) {
      if (cur && cur.kind === it.kind) cur.ids.push(it.id);
      else {
        cur = { kind: it.kind, ids: [it.id] };
        runs.push(cur.ids);
      }
    } else cur = null;
  }
  return runs;
}

export function isImageOnly(it: TranscriptItem): boolean {
  if (it.kind !== 'user' && it.kind !== 'assistant') return false;
  const parts = Array.isArray(it.parts) ? it.parts : [];
  let images = 0;
  for (const p of parts) {
    if (isImagePart(p) || isOmittedPart(p)) images++;
    else if (isTextPart(p) && p.text.trim() !== '') return false;
  }
  return images > 0;
}

/** The size a thumbnail is shown at: the long side is `long` px at most, never enlarged past the image. */
export function thumbSize(r: Pick<ImageRef, 'width' | 'height'>, long: number): { w: number; h: number } {
  const w = r.width && r.width > 0 ? r.width : 4;
  const hh = r.height && r.height > 0 ? r.height : 3;
  const k = Math.min(1, long / Math.max(w, hh));
  return { w: Math.max(24, Math.round(w * k)), h: Math.max(18, Math.round(hh * k)) };
}

/** Long side of a lone image / of one of several in a strip (both within the 480 px of the thumbnails). */
export const LONG_ALONE = 420;
export const LONG_SHARED = 240;

const kindText = (r: ImageRef): string => (r.origin === 'input' ? 'Sent by you' : r.kind === 'generated' ? 'Generated by the agent' : 'Viewed by the agent');

export interface StripHost {
  feed: ImageFeed | null;
  /** The scroller thumbnails are lazy-loaded against. */
  root: HTMLElement;
}

/** Thumbnails of one conversation view: one observer, aborted requests, the lightbox. */
export class Thumbs {
  private io: IntersectionObserver | null = null;
  private readonly pending = new Map<Element, () => void>();
  private readonly aborts = new Set<AbortController>();
  private destroyed = false;

  constructor(private readonly host: StripHost) {}

  /** A strip for `refs`, one thumbnail each; `label` names the group (a tool row's strip says whose images they are). */
  strip(refs: ImageRef[], label?: string): HTMLElement {
    const long = refs.length > 1 ? LONG_SHARED : LONG_ALONE;
    const strip = h('div', { class: 'tx-strip', role: 'group', 'aria-label': label ?? (refs.length > 1 ? `${refs.length} images` : 'Image') });
    refs.forEach((r, i) => strip.append(this.thumb(r, long, refs, i)));
    return strip;
  }

  private thumb(r: ImageRef, long: number, all: ImageRef[], index: number): HTMLElement {
    const feed = this.host.feed;
    const fetchable = !!feed && feed.canFetch(r);
    if (r.mime === 'binary' && !r.unavailable) {
      return h('span', { class: 'tx-imgchip', title: 'Bytes that are not a PNG, JPEG, GIF or WebP image' }, icon(TX_IMAGE), 'binary data');
    }
    const open = (btn: HTMLElement) => {
      if (this.destroyed) return;
      openImageLightbox({ feed, refs: all, index, onClosed: () => btn.isConnected && btn.focus({ preventScroll: true }) });
    };
    if (r.unavailable || !r.hash || !fetchable) {
      const why = unavailableText(r);
      const btn = h(
        'button',
        { class: 'tx-imgcard', 'data-origin': r.origin, title: `${why}${r.path ? `\n${r.path}` : ''}`, 'aria-label': `Image not available${r.path ? `: ${r.path}` : ''}` },
        icon(TX_IMAGE),
        h('span', { class: 'tx-imgcard-title' }, 'Image not available'),
        ...(r.path ? [h('code', { class: 'tx-imgcard-path' }, r.path)] : []),
      );
      btn.addEventListener('click', () => open(btn));
      return btn;
    }
    const { w, h: hh } = thumbSize(r, long);
    const img = h('img', { class: 'tx-img', alt: '', draggable: 'false', decoding: 'async' });
    const btn = h('button', { class: 'tx-thumb', 'data-origin': r.origin, 'data-state': 'idle', 'aria-label': `${kindText(r)}${r.width && r.height ? `, ${r.width} by ${r.height}` : ''}: enlarge`, title: `${kindText(r)}${r.width && r.height ? ` · ${r.width} × ${r.height}` : ''}` }, img);
    btn.style.width = `${w}px`;
    btn.style.aspectRatio = `${w} / ${hh}`;
    btn.addEventListener('click', () => open(btn));
    const fail = () => {
      btn.replaceWith(this.thumbFailed(r, open));
    };
    img.addEventListener('error', fail);
    // Already fetched (a row drawn again: an update of its item, a resync): shown at once, no shimmer, no second look.
    const have = feed?.thumbNow(r.hash);
    if (have) {
      img.src = have.url;
      btn.dataset.state = 'ready';
      btn.dataset.cached = '';
      if (have.width && have.height && !r.width) btn.style.aspectRatio = `${have.width} / ${have.height}`;
      return btn;
    }
    const load = () => {
      if (this.destroyed || !feed) return;
      btn.dataset.state = 'loading';
      const ac = new AbortController();
      this.aborts.add(ac);
      void feed.thumb(r.hash as string, ac.signal).then((d) => {
        this.aborts.delete(ac);
        if (this.destroyed || !btn.isConnected) return;
        if (!d) return fail();
        img.src = d.url;
        btn.dataset.state = 'ready';
        // A real size beats the bridge's guess.
        if (d.width && d.height && !r.width) btn.style.aspectRatio = `${d.width} / ${d.height}`;
      });
    };
    this.watch(btn, load);
    return btn;
  }

  private thumbFailed(r: ImageRef, open: (b: HTMLElement) => void): HTMLElement {
    const btn = h('button', { class: 'tx-imgcard', 'data-origin': r.origin, title: 'The image could not be loaded' }, icon(TX_IMAGE), h('span', { class: 'tx-imgcard-title' }, 'Image not available'), ...(r.path ? [h('code', { class: 'tx-imgcard-path' }, r.path)] : []));
    btn.addEventListener('click', () => open(btn));
    return btn;
  }

  /** Runs `load` once when `el` is near the viewport (at once without IntersectionObserver). */
  private watch(el: HTMLElement, load: () => void): void {
    if (typeof IntersectionObserver === 'undefined') {
      queueMicrotask(load);
      return;
    }
    if (!this.io) {
      this.io = new IntersectionObserver(
        (entries) => {
          for (const e of entries) {
            if (!e.isIntersecting) continue;
            this.io?.unobserve(e.target);
            const fn = this.pending.get(e.target);
            this.pending.delete(e.target);
            fn?.();
          }
        },
        { root: this.host.root, rootMargin: '240px 0px' },
      );
    }
    this.pending.set(el, load);
    this.io.observe(el);
  }

  destroy(): void {
    this.destroyed = true;
    this.io?.disconnect();
    this.io = null;
    this.pending.clear();
    for (const ac of this.aborts) ac.abort();
    this.aborts.clear();
  }
}

const TX_IMAGE = ICON.image;

export { originLabel };
